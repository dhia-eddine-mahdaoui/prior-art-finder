VERBS = ["comprises", "further includes", "additionally has", "also employs", "includes", "further comprises"]


def _cap(s: str) -> str:
    return s[0].upper() + s[1:]


def disclosure_text(e: dict) -> str:
    """Prose built from the first wording of each feature."""
    parts = [e["intro"]]
    for i, f in enumerate(e["feats"]):
        parts.append(f"The {e['noun']} {VERBS[i % len(VERBS)]} {f[0]}.")
    return " ".join(parts)
